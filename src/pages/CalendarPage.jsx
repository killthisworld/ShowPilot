import React, { useState, useEffect, useMemo } from "react";
import { supabase } from "@/api/supabaseClient";
import { useNavigate } from "react-router-dom";
import { Star, ClipboardList, Copy, X, Check, Plus, Link2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import BottomTabs from "@/components/showpilot/BottomTabs";
import StatusBadge from "@/components/showpilot/StatusBadge";
import moment from "moment";
import { clearNewShowDraft } from "@/hooks/usePersistedState";
import CalendarHeader from "@/components/showpilot/CalendarHeader";
import { calendarMonthOptions } from "@/components/showpilot/MonthDropdown";
import EventTypeIcon from "@/components/showpilot/EventTypeIcon";
import DayPhotoBands, { hasDayPhotos } from "@/components/showpilot/DayPhotoBands";
import { eventTypeColor } from "@/lib/eventTypes";
import { SCENE_FONT, SCENE_MONO, SCENE_BANKS } from "@/lib/sceneStyle";
import useIsDesktop from "@/hooks/useIsDesktop";
import StatusStrip from "@/components/showpilot/StatusStrip";
import MonthDropdown from "@/components/showpilot/MonthDropdown";
import { isDesktopNow } from "@/lib/showRoute";

function getShowAccentColor(show) {
  const typeColor = eventTypeColor(show.event_type);
  if (typeColor) return typeColor; // event type first, same colors as the home bars
  if (show.is_linked) return "#F472B6"; // pink for linked gigs
  if (show.starred) return "#FF6A00"; // amber for starred
  if (show.status === "complete") return "#8CFF3D"; // green for worked
  if (show.status === "in_progress") return "#60A5FA"; // blue for frequent/in-progress
  return "#555"; // grey for never worked
}

export default function CalendarPage() {
  const [shows, setShows] = useState([]);
  const [loading, setLoading] = useState(true);
  const [currentMonth, setCurrentMonth] = useState(moment());
  const [tmCopied, setTmCopied] = useState(false);
  const [tmLink, setTmLink] = useState(null);
  const [generatingLink, setGeneratingLink] = useState(false);
  const [dayModalKey, setDayModalKey] = useState(null);
  const [selectedDate, setSelectedDate] = useState(null);
  const [showLinkForm, setShowLinkForm] = useState(false);
  const [linkEventName, setLinkEventName] = useState("");
  const [linkEventDate, setLinkEventDate] = useState("");
  const navigate = useNavigate();
  const isDesktop = useIsDesktop();

  const handleTourManagerLink = async () => {
    setGeneratingLink(true);
    try {
      const { data: { user } } = await supabase.auth.getUser();
      if (!user) throw new Error("Not logged in");

      const { data: prefs } = await supabase
        .from("user_preferences")
        .select("display_name")
        .eq("user_id", user.id)
        .maybeSingle();

      const engineerName = prefs?.display_name || user.user_metadata?.full_name || user.user_metadata?.name || user.email || "";

      const { data: request, error } = await supabase
        .from("tour_manager_requests")
        .insert({
          engineer_user_id: user.id,
          engineer_name: engineerName,
          status: "pending",
          event_name: linkEventName.trim() || null,
          date: linkEventDate || null,
          // invite_token is auto-generated by the database (default gen_random_uuid())
        })
        .select()
        .single();

      if (error) throw error;

      const name = encodeURIComponent(engineerName || "your engineer");
      const url = `${window.location.origin}/tm-intake?token=${request.invite_token}&engineer=${user.id}&name=${name}&email=${encodeURIComponent(user.email || "")}`;
      setTmLink(url);
      setShowLinkForm(false);
      setLinkEventName("");
      setLinkEventDate("");
    } catch (e) {
      console.error(e);
    }
    setGeneratingLink(false);
  };

  const handleCopyLink = () => {
    if (tmLink) {
      navigator.clipboard.writeText(tmLink).catch(() => {});
      setTmCopied(true);
      setTimeout(() => setTmCopied(false), 1500);
    }
  };

  const handleShareMore = async () => {
    if (!tmLink) return;
    setTmLink(null);
    if (navigator.share) {
      try {
        await navigator.share({ title: "Performer Intake Link", url: tmLink });
      } catch (e) {
        // user cancelled the native share sheet — nothing to do
      }
    }
  };

  useEffect(() => {
    let isMounted = true;

    async function loadShows() {
      const { data: { user } } = await supabase.auth.getUser();
      if (!user) {
        if (isMounted) setLoading(false);
        return;
      }

      const { data, error } = await supabase
        .from("shows")
        .select("*")
        .eq("owner_id", user.id)
        .order("date", { ascending: false });

      let ownShows = error ? [] : (data || []);
      if (error) console.error("Error loading shows:", error);

      const { data: links } = await supabase
        .from("linked_gigs")
        .select("share_token")
        .eq("user_id", user.id)
        .eq("archived", false);

      if (links && links.length > 0) {
        const linkedDetails = await Promise.all(
          links.map(async (link) => {
            const { data: g } = await supabase.rpc("get_shared_gig", { p_token: link.share_token });
            return g ? { ...g, is_linked: true, share_token: link.share_token } : null;
          })
        );
        ownShows = [...ownShows, ...linkedDetails.filter(Boolean)];
      }

      if (isMounted) setShows(ownShows);
      if (isMounted) setLoading(false);
    }

    loadShows();
    return () => { isMounted = false; };
  }, []);

  // Event types live here (the desktop console is just the coming week):
  // New / Frequent / Worked / Starred / Linked. None pressed = every show.
  const [bank, setBank] = useState(null);
  const inBank = (s, id) => {
    if (id === "linked") return !!s.is_linked;
    if (id === "starred") return !!s.starred;
    return !s.is_linked && !s.starred && (s.status || "not_started") === id;
  };
  const shownShows = useMemo(() => (bank ? shows.filter((s) => inBank(s, bank)) : shows), [shows, bank]); // eslint-disable-line react-hooks/exhaustive-deps

  const showsByDate = useMemo(() => {
    const map = {};
    shownShows.forEach((s) => {
      if (s.date) {
        if (!map[s.date]) map[s.date] = [];
        map[s.date].push(s);
      }
    });
    return map;
  }, [shownShows]);

  // Month dropdown: every month around your events, with how many each has.
  const monthOptions = useMemo(() => {
    const counts = {};
    Object.entries(showsByDate).forEach(([d, list]) => { const k = d.slice(0, 7); counts[k] = (counts[k] || 0) + list.length; });
    return calendarMonthOptions({ dates: Object.keys(showsByDate), counts });
  }, [showsByDate]);
  const pickMonth = (key) => setCurrentMonth(moment(key + "-01", "YYYY-MM-DD"));

  const daysInMonth = useMemo(() => {
    const start = currentMonth.clone().startOf("month").startOf("week");
    const end = currentMonth.clone().endOf("month").endOf("week");
    const days = [];
    const d = start.clone();
    while (d.isSameOrBefore(end)) {
      days.push(d.clone());
      d.add(1, "day");
    }
    return days;
  }, [currentMonth]);

  const openShow = (show) => {
    // Your own shows open their web too (SHOW tab = the editor), job 72.
    if (show.is_linked || (show.share_token && !isDesktopNow())) navigate(`/gig/web?token=${show.share_token}`);
    else navigate(`/show/${show.id}`, { state: { from: "calendar" } });
  };

  // Lets the calendar create a new show pre-filled with a specific date,
  // so multiple shows can be added to the same day directly from here.
  const newShowOnDate = (dateKey) => {
    clearNewShowDraft();
    navigate("/show/new", { state: { from: "calendar", prefillDate: dateKey } });
  };


  const monthItems = shows.filter((x) => x.date && moment(x.date).isSame(currentMonth, "month"));
  const todayStart = moment().startOf("day");
  const nextUp = shows.filter((x) => x.date && !moment(x.date).isBefore(todayStart)).sort((a, b) => a.date.localeCompare(b.date))[0];
  const headerCells = [
    { label: "EVENTS", value: String(monthItems.length), color: "#8CFF3D" },
    { label: "NEXT UP", value: nextUp ? moment(nextUp.date).format("MMM D").toUpperCase() : "—", color: "#60A5FA" },
    { label: "STARRED", value: String(monthItems.filter((x) => x.starred).length), color: "#FF6A00" },
  ];

  const modals = (
    <>
      {/* Manager Import Link share menu */}
      {tmLink && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 px-4 h-[100dvh]" onClick={() => setTmLink(null)}>
          <div className="bg-[#161616] border border-[#2a2a2a] rounded-2xl p-2 w-full max-w-sm" onClick={(e) => e.stopPropagation()}>
            <div className="px-3 pt-3 pb-2">
              <h3 className="text-white font-bold text-base">Performer Intake</h3>
              <p className="text-white/40 text-xs mt-0.5">Share this with a performer. They'll fill out their act's info and it'll appear on your profile.</p>
            </div>
            <button onClick={handleCopyLink} className="w-full flex items-center gap-3 px-4 py-3.5 rounded-xl hover:bg-white/5 text-left">
              {tmCopied ? <Check className="w-4 h-4 text-[#8CFF3D]" /> : <Copy className="w-4 h-4 text-[#8CFF3D]" />}
              <span className="text-white text-sm font-medium">{tmCopied ? "Copied!" : "Copy Link"}</span>
            </button>
            {typeof navigator !== "undefined" && navigator.share && (
              <button onClick={handleShareMore} className="w-full flex items-center gap-3 px-4 py-3.5 rounded-xl hover:bg-white/5 text-left">
                <Copy className="w-4 h-4 text-white/60" />
                <span className="text-white text-sm font-medium">More Options...</span>
              </button>
            )}
            <button onClick={() => setTmLink(null)} className="w-full text-center py-3 mt-1 text-white/40 hover:text-white text-sm border-t border-[#2a2a2a]">
              Cancel
            </button>
          </div>
        </div>
      )}

      {/* Day list modal — shows every gig on a given date, with a way to add another */}
      {dayModalKey && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 px-4" onClick={() => setDayModalKey(null)}>
          <div className="bg-[#161616] border border-[#2a2a2a] rounded-2xl p-5 w-full max-w-md max-h-[80vh] overflow-y-auto" onClick={(e) => e.stopPropagation()}>
            <div className="flex items-center justify-between mb-3">
              <h3 className="text-white font-bold text-base">{moment(dayModalKey).format("MMMM D, YYYY")}</h3>
              <button onClick={() => setDayModalKey(null)} className="text-white/40 hover:text-white">
                <X className="w-5 h-5" />
              </button>
            </div>
            <div className="space-y-2 mb-3">
              {(showsByDate[dayModalKey] || []).map((s) => {
                const color = getShowAccentColor(s);
                return (
                  <button key={s.id} onClick={() => openShow(s)} className="w-full text-left">
                    <div className="rounded-xl border p-3 flex items-center gap-3 hover:brightness-110 transition-all" style={{ background: `linear-gradient(90deg, ${color}2e, ${color}10 55%, #111 100%)`, borderColor: color + "55" }}>
                      <EventTypeIcon type={s.event_type} imageUrl={s.icon_url} size={36} />
                      <div className="flex-1 min-w-0">
                        <div className="flex items-center gap-1.5">
                          <p className="text-white font-semibold text-base truncate leading-tight">{s.event_name || s.band_name || "Untitled Gig"}</p>
                          {s.starred && <Star className="w-3 h-3 text-amber-400 shrink-0" fill="currentColor" />}
                        </div>
                        {s.venue && <p className="text-white/50 text-[11px] truncate" style={{ fontFamily: SCENE_MONO }}>{s.venue}</p>}
                      </div>
                      <StatusBadge status={s.status} />
                    </div>
                  </button>
                );
              })}
            </div>
            <Button onClick={() => newShowOnDate(dayModalKey)} className="w-full bg-[#8CFF3D] text-black hover:bg-[#7ae62e] font-semibold rounded-xl">
              + Add another show
            </Button>
          </div>
        </div>
      )}

      {/* Name the event before generating the link */}
      {showLinkForm && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 px-4 h-[100dvh]" onClick={() => setShowLinkForm(false)}>
          <div className="bg-[#161616] border border-[#2a2a2a] rounded-2xl p-4 w-full max-w-sm" onClick={(e) => e.stopPropagation()}>
            <h3 className="text-white font-bold text-base mb-1">Performer Intake</h3>
            <p className="text-white/40 text-xs mb-3">Optional — helps you and the performer both know what this link is for.</p>
            <div className="space-y-3">
              <div>
                <label className="text-white/50 text-xs">Event Name</label>
                <input
                  value={linkEventName}
                  onChange={(e) => setLinkEventName(e.target.value)}
                  placeholder="e.g. Friday Night Live"
                  className="mt-1 block w-full min-w-0 max-w-full h-11 box-border appearance-none bg-[#111] border border-[#2a2a2a] rounded-xl px-3 text-white text-sm focus:outline-none focus:border-[#a855f7]/50 placeholder:text-white/25"
                />
              </div>
              <div>
                <label className="text-white/50 text-xs">Event Date</label>
                <input
                  type="date"
                  value={linkEventDate}
                  onChange={(e) => setLinkEventDate(e.target.value)}
                  className="mt-1 block w-full min-w-0 max-w-full h-11 box-border appearance-none bg-[#111] border border-[#2a2a2a] rounded-xl px-3 text-white text-sm focus:outline-none focus:border-[#a855f7]/50 text-left [color-scheme:dark] [&::-webkit-date-and-time-value]:text-left [&::-webkit-date-and-time-value]:min-h-[1.25rem]"
                  style={{ WebkitAppearance: "none" }}
                />
              </div>
            </div>
            <Button onClick={handleTourManagerLink} disabled={generatingLink} className="w-full font-semibold rounded-xl mt-4" style={{ backgroundColor: "#a855f7", color: "#fff" }}>
              {generatingLink ? "Generating..." : "Generate Link"}
            </Button>
            <button onClick={() => setShowLinkForm(false)} className="w-full text-center py-2.5 mt-1 text-white/40 hover:text-white text-sm">
              Cancel
            </button>
          </div>
        </div>
      )}

    </>
  );

  // Desktop (1024px+): one screen, the month fills it and the selected day's
  // shows sit in a panel on the right (same layout as the company calendar).
  if (isDesktop) {
    const todayKey = moment().format("YYYY-MM-DD");
    const activeKey = selectedDate && moment(selectedDate).isSame(currentMonth, "month")
      ? selectedDate
      : moment().isSame(currentMonth, "month") ? todayKey : null;
    const activeShows = activeKey ? (showsByDate[activeKey] || []) : [];
    const gridDays = daysInMonth.length > 35 && daysInMonth[35].isSame(currentMonth, "month") ? daysInMonth : daysInMonth.slice(0, Math.min(daysInMonth.length, 35));
    const gridRows = Math.ceil(gridDays.length / 7);
    const goToday = () => { setCurrentMonth(moment()); setSelectedDate(todayKey); };
    return (
      <div className="h-screen flex flex-col bg-[#0d0d0d] overflow-hidden" style={{ fontFamily: SCENE_FONT }}>
        {modals}
        <div className="flex items-center gap-3.5 px-6 py-3 border-b border-[#1a1a1a] shrink-0">
          <MonthDropdown
            label={currentMonth.format("MMMM YYYY")}
            value={currentMonth.format("YYYY-MM")}
            options={monthOptions}
            onSelect={pickMonth}
            className="-ml-2 px-2 py-0.5 text-white text-[32px] font-bold tracking-[0.02em]"
          />
          <button type="button" onClick={goToday} className="h-[38px] px-4 rounded-[10px] bg-[#111] border border-[#222] text-white/70 hover:text-white text-base font-semibold">Today</button>
          <div className="flex items-center gap-2 ml-2">
            {SCENE_BANKS.map((b) => {
              const on = bank === b.id;
              const n = shows.filter((x) => x.date && moment(x.date).isSame(currentMonth, "month") && inBank(x, b.id)).length;
              return (
                <button
                  key={b.id}
                  type="button"
                  aria-pressed={on}
                  onClick={() => setBank(on ? null : b.id)}
                  className="h-10 px-2.5 xl:px-3.5 rounded-full text-[16px] xl:text-[17px] font-bold tracking-[0.04em] shrink-0 whitespace-nowrap"
                  style={{ background: on ? b.color : b.color + "20", color: on ? "#0d0d0d" : b.color, border: `1.5px solid ${on ? b.color : b.color + "55"}` }}
                >
                  {b.label} <span className="text-[10px] xl:text-[11px] opacity-80" style={{ fontFamily: SCENE_MONO }}>{n}</span>
                </button>
              );
            })}
          </div>
          <button type="button" onClick={() => newShowOnDate(activeKey)} style={{ marginLeft: "auto" }} className="flex items-center gap-2 h-11 px-[18px] rounded-[10px] bg-[#8CFF3D] hover:bg-[#7ae62e] text-[#0d0d0d] text-lg font-bold shrink-0 transition-colors">
            <Plus className="w-[18px] h-[18px]" strokeWidth={2.6} /> New show
          </button>
        </div>

        <div className="flex-1 min-h-0 mx-5 mt-3.5 mb-[18px] p-4 flex gap-5 rounded-2xl border border-[#1d1d1d] overflow-hidden" style={{ backgroundColor: "#0f0f0f", backgroundImage: "radial-gradient(rgba(255,255,255,0.07) 1px, transparent 1.3px)", backgroundSize: "22px 22px", boxShadow: "inset 0 0 60px rgba(0,0,0,0.6)" }}>
          {loading ? (
            <div className="flex-1 flex items-center justify-center"><div className="w-6 h-6 border-2 border-[#8CFF3D]/30 border-t-[#8CFF3D] rounded-full animate-spin" /></div>
          ) : (
            <>
              <div className="flex-1 min-w-0 min-h-0 flex flex-col">
                <div className="grid grid-cols-7 gap-1.5 pb-1.5 shrink-0">
                  {["SUN", "MON", "TUE", "WED", "THU", "FRI", "SAT"].map((d) => (
                    <div key={d} className="text-center text-[11px] tracking-[0.12em] text-white/40" style={{ fontFamily: SCENE_MONO }}>{d}</div>
                  ))}
                </div>
                <div className="flex-1 min-h-0 grid grid-cols-7 gap-1.5" style={{ gridTemplateRows: `repeat(${gridRows}, minmax(0, 1fr))` }}>
                  {gridDays.map((day) => {
                    const key = day.format("YYYY-MM-DD");
                    const inMonth = day.isSame(currentMonth, "month");
                    const dayShows = inMonth ? (showsByDate[key] || []) : [];
                    const isToday = key === todayKey;
                    const isSel = inMonth && activeKey === key;
                    const photos = hasDayPhotos(dayShows);
                    return (
                      <div
                        key={key}
                        onClick={() => inMonth && setSelectedDate(key)}
                        onDoubleClick={() => inMonth && !dayShows.length && newShowOnDate(key)}
                        className={`relative min-w-0 min-h-0 overflow-hidden rounded-[10px] px-[7px] py-1.5 flex flex-col gap-[3px] transition-all ${inMonth ? "cursor-pointer" : ""}`}
                        style={{
                          background: isSel ? "#1b2a0e" : inMonth ? "#111" : "transparent",
                          border: isSel ? "2px solid #D2FF85" : isToday && inMonth ? "1px solid rgba(140,255,61,0.7)" : inMonth ? "1px solid #1f1f1f" : "1px solid transparent",
                          boxShadow: isSel ? "0 0 22px 4px rgba(198,255,107,0.55)" : undefined,
                        }}
                      >
                        {photos && (
                          <DayPhotoBands events={dayShows} colorOf={getShowAccentColor} keyOf={(x) => x.id || x.share_token} onOpen={openShow} max={3} titleClass="text-[13px]" />
                        )}
                        <div className="relative z-10 flex items-center justify-between pointer-events-none">
                          <span className="text-sm font-semibold" style={{ fontFamily: SCENE_MONO, color: isSel ? "#D2FF85" : isToday && inMonth ? "#8CFF3D" : photos ? "#fff" : inMonth ? "rgba(255,255,255,0.7)" : "rgba(255,255,255,0.15)", textShadow: photos ? "0 1px 3px rgba(0,0,0,0.9)" : undefined }}>{day.date()}</span>
                          {isToday && inMonth && <span className="text-[9px] tracking-[0.08em] text-[#8CFF3D]" style={{ fontFamily: SCENE_MONO, textShadow: photos ? "0 1px 3px rgba(0,0,0,0.9)" : undefined }}>TODAY</span>}
                        </div>
                        {!photos && dayShows.slice(0, 3).map((x) => {
                          const color = getShowAccentColor(x);
                          return (
                            <button
                              key={x.id || x.share_token}
                              type="button"
                              onClick={(e) => { e.stopPropagation(); openShow(x); }}
                              className="text-left min-w-0 px-1.5 py-0.5 rounded"
                              style={{ background: color + "26", borderLeft: `3px solid ${color}` }}
                            >
                              <span className="block text-[13px] font-semibold leading-[1.15] text-white truncate">{x.event_name || x.band_name || "Untitled Gig"}</span>
                            </button>
                          );
                        })}
                        {!photos && dayShows.length > 3 && <span className="text-[10px] text-white/45" style={{ fontFamily: SCENE_MONO }}>+{dayShows.length - 3} more</span>}
                      </div>
                    );
                  })}
                </div>
              </div>

              <div className="w-[340px] shrink-0 min-h-0 flex flex-col bg-[#151515] border border-[#262626] rounded-md" style={{ boxShadow: "0 16px 36px rgba(0,0,0,0.6)" }}>
                <div className="px-[18px] pt-4 pb-2.5 shrink-0">
                  <div className="text-[11px] tracking-[0.12em] text-white/45" style={{ fontFamily: SCENE_MONO }}>SELECTED DAY</div>
                  <div className="text-[28px] font-bold leading-[1.1] mt-0.5 text-white">{activeKey ? moment(activeKey).format("ddd, MMM D") : "Pick a day"}</div>
                  <div className="text-[11px] text-white/50 mt-[3px]" style={{ fontFamily: SCENE_MONO }}>
                    {activeKey ? (activeShows.length ? `${activeShows.length} ${activeShows.length === 1 ? "SHOW" : "SHOWS"}` : "NO SHOWS") : "SELECT A DAY ON THE CALENDAR"}
                  </div>
                </div>
                <div className="flex-1 min-h-0 overflow-y-auto border-t border-dashed border-[#2a2a2a] p-3.5 flex flex-col gap-2.5">
                  {activeShows.map((x) => {
                    const title = x.event_name || x.band_name || "Untitled Gig";
                    const location = [x.venue, [x.city, x.state].filter(Boolean).join(", ") || x.location].filter(Boolean).join(" · ");
                    const color = getShowAccentColor(x);
                    return (
                      <button key={x.id || x.share_token} type="button" onClick={() => openShow(x)} className="flex items-stretch gap-2.5 px-3 py-2.5 rounded-md bg-[#1a1a1a] hover:bg-[#202020] border border-[#262626] text-left transition-colors">
                        <span className="w-1 rounded-sm shrink-0" style={{ background: color }} />
                        <EventTypeIcon type={x.event_type} imageUrl={x.icon_url} size={34} />
                        <div className="min-w-0 flex-1">
                          <div className="flex items-center gap-1.5">
                            {x.is_linked && <Link2 className="w-3 h-3 shrink-0" style={{ color }} />}
                            <p className="text-white text-[19px] font-semibold leading-[1.1] truncate">{title}</p>
                            {x.starred && <Star className="w-3.5 h-3.5 text-[#FF6A00] shrink-0" fill="currentColor" />}
                          </div>
                          {location && <p className="text-[10px] tracking-[0.04em] text-white/50 mt-[3px] truncate uppercase" style={{ fontFamily: SCENE_MONO }}>{location}</p>}
                          <div className="mt-1.5"><StatusBadge status={x.status} /></div>
                        </div>
                      </button>
                    );
                  })}
                  {activeKey && activeShows.length === 0 && <p className="text-base text-white/35 text-center py-5">Nothing on this day yet.</p>}
                </div>
                <div className="px-[18px] pt-3 pb-4 shrink-0 border-t border-dashed border-[#2a2a2a] flex flex-col gap-2">
                  {activeKey && (
                    <button type="button" onClick={() => newShowOnDate(activeKey)} className="w-full py-2.5 rounded-lg text-[17px] font-bold text-[#8CFF3D] hover:bg-[#8CFF3D]/15 transition-colors" style={{ border: "1px dashed rgba(140,255,61,0.55)", background: "rgba(140,255,61,0.08)" }}>
                      + Add show on this day
                    </button>
                  )}
                  <button type="button" onClick={() => { setLinkEventDate(activeKey || ""); setShowLinkForm(true); }} disabled={generatingLink} className="w-full py-2.5 rounded-lg text-[16px] font-bold text-white flex items-center justify-center gap-2 disabled:opacity-50" style={{ background: "#a855f7" }}>
                    <ClipboardList className="w-4 h-4" /> {generatingLink ? "Generating..." : "Create intake link"}
                  </button>
                </div>
              </div>
            </>
          )}
        </div>
        <BottomTabs />
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-[#0d0d0d] pb-24" style={{ fontFamily: SCENE_FONT }}>
      {modals}

      <CalendarHeader
        monthLabel={currentMonth.format("MMMM YYYY")}
        monthKey={currentMonth.format("YYYY-MM")}
        monthOptions={monthOptions}
        onPickMonth={pickMonth}
        onPrev={() => setCurrentMonth((m) => m.clone().subtract(1, "month"))}
        onNext={() => setCurrentMonth((m) => m.clone().add(1, "month"))}
        cells={headerCells}
      />

      <div className="px-4 pt-4 max-w-lg mx-auto">
        {loading ? (
          <div className="flex justify-center py-20">
            <div className="w-6 h-6 border-2 border-[#8CFF3D]/30 border-t-[#8CFF3D] rounded-full animate-spin" />
          </div>
        ) : (
          <div>
            <div className="grid grid-cols-7 gap-1.5 mb-2">
              {["S","M","T","W","T","F","S"].map((d, i) => (
                <div key={i} className="text-center text-sm text-white/30 font-medium py-1">{d}</div>
              ))}
            </div>
            <div className="grid grid-cols-7 gap-1.5">
              {daysInMonth.map((day) => {
                const key = day.format("YYYY-MM-DD");
                const dayShows = showsByDate[key] || [];
                const isCurrentMonth = day.isSame(currentMonth, "month");
                const isToday = day.isSame(moment(), "day");
                const hasShows = dayShows.length > 0;
                const photos = isCurrentMonth && hasDayPhotos(dayShows);

                return (
                  <div
                    key={key}
                    onClick={() => {
                      if (!isCurrentMonth) return;
                      if (selectedDate === key) {
                        if (hasShows) setDayModalKey(key);
                        else newShowOnDate(key);
                      } else {
                        setSelectedDate(key);
                      }
                    }}
                    className={`relative rounded-xl overflow-hidden transition-all duration-150 ${isCurrentMonth ? "bg-[#111111] border border-[#1f1f1f] cursor-pointer hover:bg-[#161616]" : "bg-transparent"} ${isToday && isCurrentMonth ? "!border-[#8CFF3D]/70" : ""} ${selectedDate === key ? "!bg-[#1b2a0e] !border-[#D2FF85] ring-[3px] ring-[#D2FF85] shadow-[0_0_26px_6px_#C6FF6BAA] scale-[1.05] z-10" : ""}`}
                    style={{ minHeight: hasShows ? "92px" : "68px" }}
                  >
                    {photos && (
                      <DayPhotoBands events={dayShows} colorOf={getShowAccentColor} keyOf={(x) => x.id} max={2} titleClass="text-[10px]" showTitles={dayShows.length === 1} />
                    )}
                    <div className="relative z-10 px-1.5 pt-1.5">
                      <span className={`text-[13px] font-medium ${selectedDate === key ? "text-[#D2FF85] font-bold" : isToday ? "text-[#8CFF3D] font-bold" : photos ? "text-white font-bold" : isCurrentMonth ? "text-white/60" : "text-white/15"}`} style={{ fontFamily: SCENE_MONO, textShadow: photos ? "0 1px 3px rgba(0,0,0,0.9)" : undefined }}>
                        {day.date()}
                      </span>
                    </div>
                    {!photos && dayShows.slice(0, 2).map((s) => {
                      const color = getShowAccentColor(s);
                      return (
                        <div key={s.id} className="w-full mt-1 px-1.5 pb-0.5">
                          <div className="rounded-md px-1.5 py-1 text-left" style={{ backgroundColor: color + "22", borderLeft: `2px solid ${color}` }}>
                            <p className="text-[11px] font-medium leading-tight truncate" style={{ color }}>
                              {s.event_name || s.band_name || "Untitled Gig"}
                            </p>
                            {s.venue && <p className="text-[10px] text-white/30 truncate leading-tight">{s.venue}</p>}
                          </div>
                        </div>
                      );
                    })}
                    {!photos && dayShows.length > 2 && (
                      <p className="w-full px-1.5 pb-1 text-[10px] text-white/30 text-center">
                        +{dayShows.length - 2} more
                      </p>
                    )}
                  </div>
                );
              })}
            </div>
          </div>
        )}
      </div>

      <div className="px-4 pt-4 pb-2 max-w-lg mx-auto">
        <Button onClick={() => setShowLinkForm(true)} disabled={generatingLink} className="w-full font-semibold rounded-xl" style={{ backgroundColor: "#a855f7", color: "#fff" }}>
          <ClipboardList className="w-4 h-4 mr-2" />
          {generatingLink ? "Generating..." : "Create import link"}
        </Button>
      </div>

      <BottomTabs />
    </div>
  );
}
